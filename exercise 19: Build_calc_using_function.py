#Defining a function for addition, subtraction, multiplication and division
#for addition
def add(x, y):
  z = x + y
  return z
print(add(4, 8))

#for subtraction
def subtract(x, y):
  z = x - y
  return z
print(subtract(9, 5))

#for multiplicaion
def multiply(x, y):
  z = x * y
  return z
print(multiply(12, 4))

#for division
def div(x, y):
  z = x / y
  return z
print(div(564654, 2))
