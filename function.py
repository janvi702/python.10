#defining a parameter to give an argument
def Introduction(name): #'name' is the parameter here
    print(f"Hello, My name is {name}")
    print("I am Computer science student, pursuing BTech degree")
    print()
#'janvi' and 'Nikki' and the arguments passed to the 'name' parameter
Introduction("janvi")
Introduction("Nikki")
